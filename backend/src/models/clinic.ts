import {
  DataTypes,
  Model,
  type CreationOptional,
  type ForeignKey,
  type InferAttributes,
  type InferCreationAttributes,
} from 'sequelize';
import { sequelize } from '../db/sequelize.js';
import type { User } from './identity.js';

export type DayKey =
  'monday' | 'tuesday' | 'wednesday' | 'thursday' | 'friday' | 'saturday' | 'sunday';

/** Opening hours per weekday as `HH:mm` intervals in the branch timezone; absent day = closed. */
export type OpeningHours = Partial<Record<DayKey, Array<{ open: string; close: string }>>>;

export class Location extends Model<InferAttributes<Location>, InferCreationAttributes<Location>> {
  declare id: CreationOptional<string>;
  declare slug: string;
  declare name: string;
  declare addressLine: string;
  declare locality: string;
  declare region: string;
  declare postalCode: string | null;
  declare country: CreationOptional<string>;
  declare latitude: string | null;
  declare longitude: string | null;
  declare googlePlaceId: string | null;
  declare phone: string;
  declare whatsapp: string | null;
  declare openingHours: CreationOptional<OpeningHours>;
  declare timezone: CreationOptional<string>;
  declare active: CreationOptional<boolean>;
  declare sortOrder: CreationOptional<number>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

Location.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    slug: { type: DataTypes.STRING(60), allowNull: false, unique: true },
    name: { type: DataTypes.STRING(120), allowNull: false },
    addressLine: { type: DataTypes.TEXT, allowNull: false },
    locality: { type: DataTypes.STRING(80), allowNull: false },
    region: { type: DataTypes.STRING(80), allowNull: false },
    postalCode: { type: DataTypes.STRING(12) },
    country: { type: DataTypes.STRING(2), allowNull: false, defaultValue: 'IN' },
    latitude: { type: DataTypes.DECIMAL(9, 6) },
    longitude: { type: DataTypes.DECIMAL(9, 6) },
    googlePlaceId: { type: DataTypes.STRING(80) },
    phone: { type: DataTypes.STRING(20), allowNull: false },
    whatsapp: { type: DataTypes.STRING(20) },
    openingHours: { type: DataTypes.JSONB, allowNull: false, defaultValue: {} },
    timezone: { type: DataTypes.STRING(40), allowNull: false, defaultValue: 'Asia/Kolkata' },
    active: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
    sortOrder: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'locations' },
);

export type Gender = 'female' | 'male' | 'other' | 'undisclosed';
export type PatientSource =
  | 'website'
  | 'google'
  | 'instagram'
  | 'facebook'
  | 'referral'
  | 'walk_in'
  | 'whatsapp'
  | 'phone'
  | 'other';

export class Patient extends Model<InferAttributes<Patient>, InferCreationAttributes<Patient>> {
  declare id: CreationOptional<string>;
  /** Human-friendly id (EDC-000123) generated by a database sequence. */
  declare code: CreationOptional<string>;
  declare name: string;
  declare phone: string;
  declare email: string | null;
  declare dateOfBirth: string | null;
  declare gender: Gender | null;
  declare preferredLanguage: CreationOptional<string>;
  declare source: PatientSource | null;
  declare tags: CreationOptional<string[]>;
  declare homeLocationId: ForeignKey<Location['id']> | null;
  /** Demo seed rows are flagged so they can never be mistaken for, or mixed with, real data. */
  declare isDemo: CreationOptional<boolean>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
  declare deletedAt: CreationOptional<Date | null>;
}

Patient.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    code: { type: DataTypes.STRING(16) },
    name: { type: DataTypes.STRING(120), allowNull: false },
    phone: { type: DataTypes.STRING(20), allowNull: false },
    email: { type: DataTypes.STRING(254) },
    dateOfBirth: { type: DataTypes.DATEONLY },
    gender: { type: DataTypes.ENUM('female', 'male', 'other', 'undisclosed') },
    preferredLanguage: { type: DataTypes.STRING(8), allowNull: false, defaultValue: 'en' },
    source: {
      type: DataTypes.ENUM(
        'website',
        'google',
        'instagram',
        'facebook',
        'referral',
        'walk_in',
        'whatsapp',
        'phone',
        'other',
      ),
    },
    tags: { type: DataTypes.ARRAY(DataTypes.STRING(40)), allowNull: false, defaultValue: [] },
    isDemo: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
    deletedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'patients', paranoid: true },
);

export type ConsentType =
  | 'data_processing'
  | 'whatsapp_transactional'
  | 'whatsapp_marketing'
  | 'sms'
  | 'email'
  | 'photo_use';

/** Append-only: a withdrawal is a new row with `granted: false`; the latest row per type wins. */
export class PatientConsent extends Model<
  InferAttributes<PatientConsent>,
  InferCreationAttributes<PatientConsent>
> {
  declare id: CreationOptional<string>;
  declare patientId: ForeignKey<Patient['id']>;
  declare type: ConsentType;
  declare granted: boolean;
  declare channel: 'web' | 'admin' | 'paper' | 'whatsapp';
  declare textVersion: string;
  declare ip: string | null;
  declare recordedBy: ForeignKey<User['id']> | null;
  declare createdAt: CreationOptional<Date>;
}

PatientConsent.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    type: {
      type: DataTypes.ENUM(
        'data_processing',
        'whatsapp_transactional',
        'whatsapp_marketing',
        'sms',
        'email',
        'photo_use',
      ),
      allowNull: false,
    },
    granted: { type: DataTypes.BOOLEAN, allowNull: false },
    channel: { type: DataTypes.ENUM('web', 'admin', 'paper', 'whatsapp'), allowNull: false },
    textVersion: { type: DataTypes.STRING(40), allowNull: false },
    ip: { type: DataTypes.STRING(64) },
    createdAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'patient_consents', updatedAt: false },
);

