export type LeadSource =
  'website_booking' | 'website_contact' | 'symptom_helper' | 'phone' | 'walk_in';
export type LeadStatus = 'new' | 'contacted' | 'booked' | 'lost';

export interface AppointmentRequestDetails {
  reason: string;
  preferredDate: string;
  timeOfDay: string;
  patientFor: string;
  notes: string;
}

/** An enquiry waiting for the front desk; becomes a patient/appointment once confirmed. */
export class Lead extends Model<InferAttributes<Lead>, InferCreationAttributes<Lead>> {
  declare id: CreationOptional<string>;
  /** Short human reference (REQ-00042) generated by a database sequence. */
  declare reference: CreationOptional<string>;
  declare source: LeadSource;
  declare status: CreationOptional<LeadStatus>;
  declare name: string;
  declare phone: string;
  declare locationId: ForeignKey<Location['id']> | null;
  declare details: CreationOptional<AppointmentRequestDetails | Record<string, unknown>>;
  declare consentTextVersion: string;
  declare consentedAt: Date;
  declare assignedTo: ForeignKey<User['id']> | null;
  declare patientId: ForeignKey<Patient['id']> | null;
  declare ip: string | null;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
  declare deletedAt: CreationOptional<Date | null>;
}

Lead.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    reference: { type: DataTypes.STRING(16) },
    source: {
      type: DataTypes.ENUM(
        'website_booking',
        'website_contact',
        'symptom_helper',
        'phone',
        'walk_in',
      ),
      allowNull: false,
    },
    status: {
      type: DataTypes.ENUM('new', 'contacted', 'booked', 'lost'),
      allowNull: false,
      defaultValue: 'new',
    },
    name: { type: DataTypes.STRING(120), allowNull: false },
    phone: { type: DataTypes.STRING(20), allowNull: false },
    details: { type: DataTypes.JSONB, allowNull: false, defaultValue: {} },
    consentTextVersion: { type: DataTypes.STRING(40), allowNull: false },
    consentedAt: { type: DataTypes.DATE, allowNull: false },
    ip: { type: DataTypes.STRING(64) },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
    deletedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'leads', paranoid: true },
);
