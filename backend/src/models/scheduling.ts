import {
  DataTypes,
  Model,
  type CreationOptional,
  type ForeignKey,
  type InferAttributes,
  type InferCreationAttributes,
  type NonAttribute,
} from 'sequelize';
import { sequelize } from '../db/sequelize.js';
import type { Location, OpeningHours, Patient } from './clinic.js';
import type { User } from './identity.js';

/** Bookable hours for one branch. Online slots are generated from this, never stored. */
export class LocationSchedule extends Model<
  InferAttributes<LocationSchedule>,
  InferCreationAttributes<LocationSchedule>
> {
  declare id: CreationOptional<string>;
  declare locationId: ForeignKey<Location['id']>;
  declare active: CreationOptional<boolean>;
  declare slotMinutes: CreationOptional<number>;
  declare capacity: CreationOptional<number>;
  declare weekly: CreationOptional<OpeningHours>;
  declare minNoticeMinutes: CreationOptional<number>;
  declare maxDaysAhead: CreationOptional<number>;
  declare updatedBy: ForeignKey<User['id']> | null;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

LocationSchedule.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    active: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
    slotMinutes: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 30 },
    capacity: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 1 },
    weekly: { type: DataTypes.JSONB, allowNull: false, defaultValue: {} },
    minNoticeMinutes: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 120 },
    maxDaysAhead: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 60 },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'location_schedules' },
);

/** A day a branch is closed (festival, staff leave covering the whole clinic, etc.). */
export class Holiday extends Model<InferAttributes<Holiday>, InferCreationAttributes<Holiday>> {
  declare id: CreationOptional<string>;
  declare locationId: ForeignKey<Location['id']>;
  declare date: string;
  declare reason: CreationOptional<string>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

Holiday.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    date: { type: DataTypes.DATEONLY, allowNull: false },
    reason: { type: DataTypes.STRING(120), allowNull: false, defaultValue: '' },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'holidays' },
);

export const APPOINTMENT_STATUSES = [
  'pending',
  'confirmed',
  'checked_in',
  'completed',
  'no_show',
  'cancelled',
] as const;
export type AppointmentStatus = (typeof APPOINTMENT_STATUSES)[number];
export type AppointmentSource = 'website' | 'admin' | 'phone' | 'walk_in' | 'whatsapp';

/** Statuses that occupy a slot (everything except cancelled). */
export const SLOT_HOLDING: AppointmentStatus[] = [
  'pending',
  'confirmed',
  'checked_in',
  'completed',
  'no_show',
];

export class Appointment extends Model<
  InferAttributes<Appointment>,
  InferCreationAttributes<Appointment>
> {
  declare id: CreationOptional<string>;
  /** Human reference (APT-00042) generated by a database sequence. */
  declare reference: CreationOptional<string>;
  declare patientId: ForeignKey<Patient['id']>;
  declare locationId: ForeignKey<Location['id']>;
  declare startAt: Date;
  declare endAt: Date;
  declare status: CreationOptional<AppointmentStatus>;
  declare source: AppointmentSource;
  declare reason: string;
  declare notes: CreationOptional<string>;
  declare confirmedAt: CreationOptional<Date | null>;
  declare confirmedBy: ForeignKey<User['id']> | null;
  declare cancelledAt: CreationOptional<Date | null>;
  declare cancelledBy: CreationOptional<'patient' | 'clinic' | null>;
  declare createdBy: ForeignKey<User['id']> | null;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
  declare deletedAt: CreationOptional<Date | null>;

  declare patient?: NonAttribute<Patient>;
  declare location?: NonAttribute<Location>;
}

Appointment.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    reference: { type: DataTypes.STRING(16) },
    startAt: { type: DataTypes.DATE, allowNull: false },
    endAt: { type: DataTypes.DATE, allowNull: false },
    status: {
      type: DataTypes.ENUM(...APPOINTMENT_STATUSES),
      allowNull: false,
      defaultValue: 'pending',
    },
    source: {
      type: DataTypes.ENUM('website', 'admin', 'phone', 'walk_in', 'whatsapp'),
      allowNull: false,
    },
    reason: { type: DataTypes.STRING(60), allowNull: false },
    notes: { type: DataTypes.TEXT, allowNull: false, defaultValue: '' },
    confirmedAt: { type: DataTypes.DATE },
    cancelledAt: { type: DataTypes.DATE },
    cancelledBy: { type: DataTypes.ENUM('patient', 'clinic') },
    createdAt: DataTypes.DATE,
    updatedAt: DataTypes.DATE,
    deletedAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'appointments', paranoid: true },
);

/** Single-use, short-lived email sign-in links for the patient portal (stored hashed). */
export class PatientLoginLink extends Model<
  InferAttributes<PatientLoginLink>,
  InferCreationAttributes<PatientLoginLink>
> {
  declare id: CreationOptional<string>;
  declare email: string;
  declare tokenHash: string;
  declare expiresAt: Date;
  declare usedAt: CreationOptional<Date | null>;
  declare ip: string | null;
  declare createdAt: CreationOptional<Date>;
}

PatientLoginLink.init(
  {
    id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
    email: { type: DataTypes.STRING(254), allowNull: false },
    tokenHash: { type: DataTypes.STRING(64), allowNull: false, unique: true },
    expiresAt: { type: DataTypes.DATE, allowNull: false },
    usedAt: { type: DataTypes.DATE },
    ip: { type: DataTypes.STRING(64) },
    createdAt: DataTypes.DATE,
  },
  { sequelize, tableName: 'patient_login_links', updatedAt: false },
);
